public class datatype {
    public static void main(String[] args) {
        //arithmetic operators
        int a=10;
        int b=3;
        
System.out.println(a+b);
System.out.println(a-b);
System.out.println(a/b);
// in java when we divide two integers the result is also an integer and the decimal part is truncated
System.out.println(a*b);
System.out.println(a%b);//modulus operator gives the remainder of the division
//output will be 1 because 10 divided by 3 gives 3 with a remainder of 1
    }

// in java we have different data types like int, float, double, char, boolean 
// int is used to store whole numbers,

float y=3.14f;
 // we need to add f at the end of the number to indicate that it is a float

 double z=3.14;
 // double is used to store decimal numbers with double precision

 // float and double are used to store decimal numbers,
//  char is used to store single characters and boolean is used to store true or false values
char c='A';
boolean isJavaFun=true;
// we can also use arithmetic operators with variables and the result will be stored in the variable
}